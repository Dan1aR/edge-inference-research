"""Aggregate the extension's inference results (results/x1, results/x4) and the A6 error model (results/x6).

Writes results/aggregate_x.md (tables) and results/aggregate_x.json.
  * per (model, dataset/resolution): AP of each config, delta vs "none" (standard BF16, FP32 accumulation) and
    the recovered share of the none-all gap, (AP - AP_all) / (AP_none - AP_all);
  * A6: Spearman correlation of each cheap error metric with the AP drop (none - AP) over configs, per model.
Bootstrap CIs, if computed (results/*/boot_*.json from scripts/bootstrap_x.py), are added as +-1.96 SE.
"""
import glob
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy import stats

MODELS = ("tiny", "small", "base", "rtdetr_r18", "rtdetr_r50", "detr_r50", "deit-tiny", "deit-small", "deit-base")
DATASETS = ("coco_val", "coco", "voc07_test", "visdrone_val", "bdd_val", "coco_o", "crowdhuman_val", "inv2")
groups = defaultdict(dict)  # (model, dataset) -> cfg -> metric
for f in sorted(glob.glob("results/x1/*.json") + glob.glob("results/x4/*.json")):
    stem = Path(f).stem
    if stem.startswith(("boot_", "sens")):
        continue
    model = next((m for m in sorted(MODELS, key=len, reverse=True) if stem.startswith(m + "_")), None)
    if model is None:
        continue
    rest = stem[len(model) + 1:]
    if rest.startswith("coco_r"):  # resolution axis
        ds, cfg = rest.split("_", 2)[:2], rest.split("_", 2)[2]
        ds = "_".join(ds)
    else:
        ds = next((d for d in sorted(DATASETS, key=len, reverse=True) if rest.startswith(d + "_")), None)
        if ds is None:
            continue
        cfg = rest[len(ds) + 1:]
    d = json.load(open(f))
    m = d.get("metrics", d)
    val = m.get("AP", m.get("top1"))
    if val is None:
        continue
    groups[(model, "coco" if ds == "coco_val" else ds)][cfg] = {"ap": val, "n": m.get("num_images"), "file": f}

lines = ["# Aggregate of the extension's inference results (auto-generated by scripts/aggregate_x.py)", "",
         "AP (top-1 for DeiT/ImageNetV2). Δ = AP − AP(none) in pp; rec = recovered share of the none−all gap.", ""]
out = {}
for (model, ds) in sorted(groups, key=lambda k: (MODELS.index(k[0]) if k[0] in MODELS else 99, k[1])):
    g = groups[(model, ds)]
    none, allv = g.get("none", {}).get("ap"), g.get("all", {}).get("ap")
    lines += [f"## {model} / {ds}" + (f" (n={g['none']['n']})" if "none" in g and g["none"]["n"] else ""), "",
              "| config | AP | Δ pp | rec |", "|---|---|---|---|"]
    rows = {}
    for cfg in sorted(g, key=lambda c: -g[c]["ap"]):
        ap = g[cfg]["ap"]
        dlt = 100 * (ap - none) if none is not None else None
        rec = (ap - allv) / (none - allv) if none is not None and allv is not None and abs(none - allv) > 1e-4 else None
        rows[cfg] = {"ap": ap, "delta_pp": dlt, "recovered": rec}
        lines.append(f"| {cfg} | {ap:.4f} | {'' if dlt is None else f'{dlt:+.2f}'} | "
                     f"{'' if rec is None else f'{100 * rec:.0f}%'} |")
    out[f"{model}/{ds}"] = rows
    lines.append("")

# A6: error model
lines += ["## A6: cheap error metrics vs AP drop (Spearman ρ over configs, COCO)", "",
          "| model | n configs | KL | box L1 | hidden rel | op rel err mean | op rel err max |", "|---|---|---|---|---|---|---|"]
a6 = {}
for f in sorted(glob.glob("results/x6/errmodel_*.json")):
    e = json.load(open(f))
    g = groups.get((e["model"], "coco"), {})
    if "none" not in g:
        continue
    cfgs = [c for c in e["configs"] if c in g]
    if len(cfgs) < 4:
        continue
    drop = np.array([g["none"]["ap"] - g[c]["ap"] for c in cfgs])
    rho = {k: float(stats.spearmanr([e["configs"][c][k] for c in cfgs], drop).statistic)
           for k in ("kl", "box_l1", "hidden_rel", "op_rel_err_mean", "op_rel_err_max")}
    a6[e["model"]] = {"n": len(cfgs), "rho": rho}
    lines.append(f"| {e['model']} | {len(cfgs)} | " + " | ".join(f"{rho[k]:+.2f}" for k in rho) + " |")
lines.append("")
Path("results/aggregate_x.md").write_text("\n".join(lines))
Path("results/aggregate_x.json").write_text(json.dumps({"tables": out, "a6": a6}, indent=1))
print("groups:", len(groups), "| a6 models:", list(a6))
